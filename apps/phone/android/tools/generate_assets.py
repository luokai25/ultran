#!/usr/bin/env python3
"""Generate the Ultran launcher icons and splash screens.

The Android project is committed as text. Its raster assets are generated here
instead of being checked in, so the repository carries no opaque binaries and
the artwork is reviewable as code.

Run from `apps/phone/android`:

    python3 tools/generate_assets.py

Requires Pillow (`pip install pillow`). CI installs it before the Gradle build.
"""

from __future__ import annotations

import os
import sys

try:
    from PIL import Image, ImageDraw
except ImportError:  # pragma: no cover - CI installs Pillow explicitly
    sys.exit("Pillow is required: pip install pillow")

VOID = (5, 5, 5)
OBSIDIAN = (11, 11, 13)
CARBON = (19, 19, 23)
GOLD = (212, 175, 55)
GOLD_BRIGHT = (245, 215, 110)
GOLD_DEEP = (138, 109, 31)

RES = "app/src/main/res"

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

SPLASHES = {
    "drawable/splash.png": (480, 800),
    "drawable-port-mdpi/splash.png": (320, 480),
    "drawable-port-hdpi/splash.png": (480, 800),
    "drawable-port-xhdpi/splash.png": (720, 1280),
    "drawable-port-xxhdpi/splash.png": (960, 1600),
    "drawable-port-xxxhdpi/splash.png": (1280, 1920),
    "drawable-land-mdpi/splash.png": (480, 320),
    "drawable-land-hdpi/splash.png": (800, 480),
    "drawable-land-xhdpi/splash.png": (1280, 720),
    "drawable-land-xxhdpi/splash.png": (1600, 960),
    "drawable-land-xxxhdpi/splash.png": (1920, 1280),
}

# ---------------------------------------------------------------------------
# The Ultran mark: a faceted gold war-helm with two slanted sensor eyes.
#
# Geometry lives here once, in a 108x108 viewport (the Android adaptive-icon
# grid, with the helm inside the 66-unit safe zone). The PNG icons, the splash
# screens and the adaptive-icon vector are all produced from these polygons, and
# apps/phone/src/mark.ts carries the same numbers for the in-app mark.
# ---------------------------------------------------------------------------

Poly = list[tuple[float, float]]
VIEWPORT = 108.0

SHELL: Poly = [(54, 22), (75, 31), (81, 53), (70, 76), (54, 87), (38, 76), (27, 53), (33, 31)]
FACET_LIGHT: Poly = [(54, 22), (75, 31), (54, 44), (33, 31)]
FACET_DEEP: Poly = [(81, 53), (70, 76), (54, 87), (54, 60)]
FACE: Poly = [(54, 36), (68, 41), (71, 54), (63, 69), (54, 74), (45, 69), (37, 54), (40, 41)]
EYE_L: Poly = [(40, 49), (51, 53), (51, 58), (41, 55)]
EYE_R: Poly = [(57, 53), (68, 49), (67, 55), (57, 58)]
GRILLE: list[Poly] = [
    [(48, 65), (60, 65), (60, 67), (48, 67)],
    [(49, 69), (59, 69), (59, 70.6), (49, 70.6)],
]
CREST: Poly = [(53, 22), (55, 22), (55, 35), (53, 35)]

LAYERS: list[tuple[Poly, tuple[int, int, int]]] = [
    (SHELL, GOLD),
    (FACET_LIGHT, GOLD_BRIGHT),
    (FACET_DEEP, GOLD_DEEP),
    (FACE, CARBON),
    (EYE_L, GOLD_BRIGHT),
    (EYE_R, GOLD_BRIGHT),
    *[(g, GOLD_DEEP) for g in GRILLE],
    (CREST, OBSIDIAN),
]

SS = 4  # supersampling factor, so the facets are antialiased without gradients


def _hex(rgb: tuple[int, int, int]) -> str:
    return "#{:02X}{:02X}{:02X}".format(*rgb)


def _scaled(poly: Poly, scale: float, ox: float, oy: float) -> list[tuple[float, float]]:
    return [(ox + x * scale, oy + y * scale) for x, y in poly]


def draw_mark(img: Image.Image, size: float, ox: float, oy: float) -> None:
    """Draw the helm into ``img`` so the 108-unit viewport maps to ``size`` px."""
    draw = ImageDraw.Draw(img)
    scale = size / VIEWPORT
    for poly, colour in LAYERS:
        draw.polygon(_scaled(poly, scale, ox, oy), fill=colour)


def mark(size: int, background: tuple[int, int, int], fill_ratio: float = 1.0) -> Image.Image:
    """The helm on a dark field. ``fill_ratio`` scales the 108-unit viewport."""
    big = size * SS
    img = Image.new("RGB", (big, big), background)
    viewport = big * fill_ratio
    draw_mark(img, viewport, (big - viewport) / 2, (big - viewport) / 2)
    return img.resize((size, size), Image.LANCZOS)


def vector_drawable() -> str:
    """The adaptive-icon foreground, emitted from the same polygons."""
    paths = []
    for poly, colour in LAYERS:
        if colour == OBSIDIAN:
            # Obsidian is the icon background; as a vector layer it is a cut-out.
            colour = OBSIDIAN
        data = "M" + " L".join(f"{x:g},{y:g}" for x, y in poly) + " Z"
        paths.append(
            f'    <path android:fillColor="{_hex(colour)}"\n        android:pathData="{data}" />'
        )
    body = "\n".join(paths)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- GENERATED by tools/generate_assets.py - edit the polygons there. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f"{body}\n</vector>\n"
    )


def splash(width: int, height: int) -> Image.Image:
    img = Image.new("RGB", (width, height), VOID)
    draw = ImageDraw.Draw(img)
    cx, cy = width / 2, height / 2

    # A soft glow, built from concentric ellipses so it needs no gradient support.
    for step in range(28, 0, -1):
        t = step / 28
        radius = min(width, height) * 0.42 * t
        shade = (
            int(5 + 18 * (1 - t)),
            int(5 + 14 * (1 - t)),
            int(5 + 6 * (1 - t)),
        )
        draw.ellipse([cx - radius, cy - radius, cx + radius, cy + radius], fill=shade)

    # Draw the helm directly on the glow (supersampled), not as a pasted tile,
    # so no square edge shows against the gradient.
    side = min(width, height) * 0.46
    big = img.resize((width * 2, height * 2), Image.LANCZOS)
    draw_mark(big, side * 2, cx * 2 - side, cy * 2 - side)
    return big.resize((width, height), Image.LANCZOS)


def transparent_foreground(size: int) -> Image.Image:
    """Adaptive-icon foreground: the mark on transparency, inside the safe zone."""
    logo = mark(int(size * 0.92), OBSIDIAN).convert("RGBA")
    pixels = logo.load()
    for y in range(logo.height):
        for x in range(logo.width):
            r, g, b, _ = pixels[x, y]
            if abs(r - OBSIDIAN[0]) < 6 and abs(g - OBSIDIAN[1]) < 6 and abs(b - OBSIDIAN[2]) < 6:
                pixels[x, y] = (0, 0, 0, 0)

    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(logo, ((size - logo.width) // 2, (size - logo.height) // 2), logo)
    return canvas


def main() -> None:
    if not os.path.isdir(RES):
        sys.exit(f"run this from apps/phone/android (no {RES} here)")

    for density, px in DENSITIES.items():
        out = os.path.join(RES, f"mipmap-{density}")
        os.makedirs(out, exist_ok=True)
        mark(px, OBSIDIAN, 0.86).save(os.path.join(out, "ic_launcher.png"), optimize=True)
        mark(px, OBSIDIAN, 0.78).save(os.path.join(out, "ic_launcher_round.png"), optimize=True)
        transparent_foreground(px).save(
            os.path.join(out, "ic_launcher_foreground.png"), optimize=True
        )

    for path, (width, height) in SPLASHES.items():
        full = os.path.join(RES, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        # A flat dark field with a small mark quantises to a tiny palette PNG.
        splash(width, height).quantize(colors=64, method=Image.MEDIANCUT).save(
            full, optimize=True
        )

    vector = os.path.join(RES, "drawable-v24", "ic_launcher_foreground.xml")
    os.makedirs(os.path.dirname(vector), exist_ok=True)
    with open(vector, "w", encoding="utf-8") as handle:
        handle.write(vector_drawable())

    total = 0
    for root, _, files in os.walk(RES):
        for name in files:
            total += os.path.getsize(os.path.join(root, name))
    print(f"generated launcher icons and {len(SPLASHES)} splash screens ({total} bytes)")


if __name__ == "__main__":
    main()
